def _post(v):
    """Vectors (a letter with the arrow U+20D7) in FreeSerif's italic (.vec: the other faces have no arrow); the ellipsis of
    a formula ('1,2,3,…') in the Latin math face (.mth), on the line, not centred as the CJK faces set it."""
    out = []
    for x in ([v] if isinstance(v, str) else v):
        if isinstance(x, dict):                                   # (MathML)
            out.append(x)
            continue
        t, c = (x, '') if isinstance(x, str) else x
        if '⃗' in t:
            out.append((t, (c + ' vec').strip()))
            continue
        for k, part in enumerate(t.split('…')):
            if k:
                out.append(('…', (c + ' mth').strip()))
            if part:
                out.append((part, c) if c else part)
    return out


