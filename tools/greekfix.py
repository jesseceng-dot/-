ENTRIES = B2 + B4 + B_EXTRA


_COMPILED = None


def _compile():
    out = []
    for e in sorted(ENTRIES, key=lambda e: -len(e[1])):
        books, old, new = e[0], e[1], e[2]
        left, right = (e[3], e[4]) if len(e) > 3 else ('', '')
        head = f'({re.escape(left)})' if left else f'(?<![{TOK}])()'
        tail = f'(?={re.escape(right)})' if right else f'(?![{TOK}])'
        out.append((books, old, new, re.compile(head + re.escape(old) + tail)))
    return out


def restore(text, book, stats=None):
    """Apply every entry of the given book ('2' or '4') to a plain string."""
    global _COMPILED
    if _COMPILED is None:
        _COMPILED = _compile()
    for books, old, new, pat in _COMPILED:
        if book not in books and books != '*':
            continue
        text, n = pat.subn(lambda m: m.group(1) + new, text)
        if stats is not None and n:
            stats[old] = stats.get(old, 0) + n
    return text
