_SUP, _SUB = '⁰¹²³⁴⁵⁶⁷⁸⁹⁻⁺', '₀₁₂₃₄₅₆₇₈₉'
_DIG = '0123456789'


def _scripts(v):
    out = []
    for r in ([v] if isinstance(v, str) else v):
        t, c = (r, '') if isinstance(r, str) else r
        for m in re.finditer(f'([{_SUP}]+)|([{_SUB}]+)|([^{_SUP}{_SUB}]+)', t):
            if m.group(1):
                out.append((m.group(1).translate(str.maketrans(_SUP, _DIG + '−+')), (c + ' msup').strip()))
            elif m.group(2):
                out.append((m.group(2).translate(str.maketrans(_SUB, _DIG)), (c + ' msub').strip()))
            else:
                out.append((m.group(3), c))
    return out[0][0] if len(out) == 1 and not out[0][1] else out


